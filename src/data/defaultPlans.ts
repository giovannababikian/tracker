export function getFormattedDateKey(d: Date = new Date()): string {
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function getMondayOfWeek(targetDate: Date = new Date()): Date {
  const d = new Date(targetDate);
  d.setHours(12, 0, 0, 0);
  const day = d.getDay();
  // Monday is 1; if Sunday (0), shift is 6
  const shift = (day + 6) % 7;
  d.setDate(d.getDate() - shift);
  return d;
}

export function getWeekDays(startMonday: Date): Date[] {
  return Array.from({ length: 7 }, (_, i) => {
    const d = new Date(startMonday);
    d.setDate(startMonday.getDate() + i);
    return d;
  });
}

export function isActivityScheduledForDate(activity: Activity, d: Date): boolean {
  if (!activity.active) return false;
  const dayNum = String(d.getDay()) as Activity['days'][number];
  if (activity.frequency === 'daily') return true;
  if (activity.frequency === 'weekly') return activity.days.includes(dayNum);
  if (activity.frequency === 'times') return activity.days.includes(dayNum);
  if (activity.frequency === 'monthly') return d.getDate() === 1;
  return false;
}
